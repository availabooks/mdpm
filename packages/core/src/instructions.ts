import { existsSync, promises as fs } from 'fs';
import * as path from 'path';
import { CRITERIA_HEADING, IDEA_HEADING, LOG_HEADING, PLAN_HEADING, QUESTIONS_HEADING, VERIFICATION_HEADING } from './body';
import { AgentMode } from './types';

/*
 * What agents are told about the flow: the Claude Code skill, the AGENTS.md section, and the
 * prompt the runner sends for each run. One source, so they never disagree.
 */

export const MARKER_START = '<!-- mdpm:agent-protocol:start (generated by "mdpm agent init"; edits between the markers are overwritten) -->';
export const MARKER_END = '<!-- mdpm:agent-protocol:end -->';

/** The protocol, as markdown. Headings start at level 2 so it can sit inside another document. */
export function protocolMarkdown(): string {
  return `## Working on mdpm ideas

mdpm keeps ideas as markdown files with YAML front matter, in project folders (a folder with a
\`.proj\` file). Each idea moves through a flow: **idea → plan → executing → review → done**, and
**blocked** while it waits for an answer. A person writes the idea; you plan it, they approve the
plan, you execute it, they review it. Only one idea is executed at a time.

**Change an idea's state only with \`mdpm\` commands.** They validate every write and keep the
board consistent. You may edit the idea's *body* directly (the plan, criteria, ticking
checkboxes), but not its front matter. Your name comes from \`$MDPM_AGENT\` (or \`--agent <name>\`).

### Finding work

\`\`\`bash
mdpm next --json        # what to do next: the idea and its mode, or nothing
\`\`\`

| Mode | Idea | What to do |
|---|---|---|
| \`plan\` | status idea | **Don't change code.** Read the \`## ${IDEA_HEADING}\` and the code, then write \`## ${PLAN_HEADING}\` (approach, files, steps), \`## ${CRITERIA_HEADING}\` (\`- [ ] …\` per observable outcome) and \`## ${VERIFICATION_HEADING}\` into the idea file. Finish with \`mdpm propose <id> "<summary>"\`; the person approves it. |
| \`execute\` | approved plan, or already executing | Build it on the idea's branch: commit your work, tick each acceptance criterion you meet, run the verification, then \`mdpm handoff\`. If the log shows earlier work, continue from there. |

### Commands

\`\`\`bash
mdpm propose <id> "<summary>"            # plan written: idea → plan, waits for approval
mdpm start <id>                          # take an approved plan: executing, on branch idea/<id>
mdpm log <id> "<what you did/decided>"   # progress notes, decisions, links; log as you go
mdpm block <id> "<question>" ["<question>"…]   # blocked; questions go under ## ${QUESTIONS_HEADING}
mdpm handoff <id> "<summary>" [--pr <url>]     # executing → review, for the person to check
mdpm show <id> --json                    # the idea, including its body
mdpm check --strict                      # validate everything
\`\`\`

### Rules

- **Block instead of guessing.** If the idea is ambiguous, contradicts the code, or needs a
  decision only the person can make, write precise questions with \`mdpm block\` (say what you
  found and the options you see) and stop. Don't invent requirements.
- **People decide.** Never approve a plan, accept work, or move an idea yourself; the CLI refuses
  \`approve\`, \`accept\`, \`rework\`, \`unblock\` and \`move\` while \`MDPM_AGENT\` is set.
- **One idea at a time.** Work only on the idea you were given; note anything else in its \`## ${LOG_HEADING}\`.
- **Work on the idea's branch.** Commit your changes there; never push to or commit on the default branch.
- **Leave a trail.** Before you stop, the idea must have a new log entry, a proposal, a handoff,
  or a block, so the person (or your next run) can pick up from the file alone.
- Keep the idea valid: \`mdpm check --strict\` must pass for it.
`;
}

const MODE_INSTRUCTIONS: Record<AgentMode, string> = {
  plan: `Mode: plan. Do NOT change any code. Turn the idea into a plan the person can approve and you can later execute unattended: read the "${IDEA_HEADING}" section and the relevant code, then write "${PLAN_HEADING}" (approach, the files to change, the steps), "${CRITERIA_HEADING}" as "- [ ] …" items (one per observable outcome) and "${VERIFICATION_HEADING}" (commands or tests) into the idea file's body. Finish with \`mdpm propose <id> "<one-line summary>"\`. If you can't plan it without an answer, finish with \`mdpm block <id> "<question>"…\` instead.`,
  execute: `Mode: execute. Build the approved plan on the current branch: make the changes, commit them, tick each acceptance criterion you meet in the idea's body, run the verification, then \`mdpm handoff <id> "<summary>"\`. Block with questions instead of guessing.`,
};

export interface PromptInput {
  agent: string;
  mode: AgentMode;
  /** Continue an execution an earlier run started. */
  resume?: boolean;
  taskId: string;
  /** Absolute path of the idea file in the main checkout. */
  taskFile: string;
  /** Contents of the idea file. */
  taskText: string;
  /** Main checkout, where idea state lives (MDPM_ROOT). */
  root: string;
  /** The agent worktree, where code is read and changed. */
  worktree: string;
  /** The idea's branch (execute), or the default branch checked out detached (plan). */
  branch: string;
}

/** The prompt for one run: the protocol, the mode, the paths, and the idea itself. */
export function buildPrompt(p: PromptInput): string {
  const where =
    p.mode === 'plan'
      ? `- Your working directory is a git worktree with "${p.branch}" checked out (detached). Read the code there; don't change it.`
      : `- Your working directory is a git worktree on branch "${p.branch}". Make and commit code changes there.`;
  const finish = p.mode === 'plan' ? `mdpm propose ${p.taskId} "<summary>" · mdpm block ${p.taskId} "<question>"` : `mdpm handoff ${p.taskId} "<summary>" · mdpm block ${p.taskId} "<question>"`;
  const resume = p.resume ? `\nAn earlier run started executing this idea and stopped before finishing. Read its "${LOG_HEADING}" and the commits on this branch, then continue where it left off.\n` : '';
  return `You are ${p.agent}, working unattended on an mdpm idea. Nobody is watching this run, so don't ask for confirmation: act, and when you need a decision from the person, block the idea with questions.

${MODE_INSTRUCTIONS[p.mode].replace(/<id>/g, p.taskId)}
${resume}
- Idea id: ${p.taskId}
- Idea file (edit its body here, not the copy in your working directory): ${p.taskFile}
${where}
- Idea state lives in the main checkout at ${p.root} (MDPM_ROOT is set, so mdpm commands use it).
- Finish with exactly one of: ${finish}.

${protocolMarkdown()}
## The idea

\`\`\`\`markdown
${p.taskText.trim()}
\`\`\`\`
`;
}

/** Replaces the generated block between the markers in `existing`, or appends it. */
export function upsertMarked(existing: string, content: string): string {
  const block = `${MARKER_START}\n${content.trim()}\n${MARKER_END}`;
  const start = existing.indexOf(MARKER_START.slice(0, 30));
  const end = existing.indexOf(MARKER_END);
  if (start >= 0 && end > start) return existing.slice(0, start) + block + existing.slice(end + MARKER_END.length);
  const sep = existing.trim() ? (existing.endsWith('\n') ? '\n' : '\n\n') : '';
  return `${existing}${sep}${block}\n`;
}

/** Opening message of an interactive session a person starts on an idea (`mdpm agent continue`). */
export function buildContinuePrompt(p: Pick<PromptInput, 'agent' | 'taskId' | 'taskFile' | 'taskText' | 'root' | 'worktree' | 'branch'>): string {
  return `You are ${p.agent}. A person is here with you now, working on an mdpm idea. Read the idea below, including its plan, "${LOG_HEADING}", questions and any earlier work on "${p.branch}", then tell them in two or three sentences where things stand and ask what they want next. Don't start new work until they say so.

- Idea id: ${p.taskId}
- Idea file (idea state lives here; edit its body, change front matter only with mdpm commands): ${p.taskFile}
- Your working directory is the agent's git worktree, on "${p.branch}". Make and commit code changes there.
- MDPM_ROOT is set to ${p.root}, so mdpm commands use the main checkout. Log what you do with mdpm log ${p.taskId} "<text>"; when the person says the work is done, hand it off with mdpm handoff ${p.taskId} "<summary>". The person approves, accepts and moves ideas; you don't.

\`\`\`\`markdown
${p.taskText.trim()}
\`\`\`\`
`;
}

const SKILL_FRONT = `---
name: mdpm
description: Plan and execute mdpm ideas (markdown files with front matter in folders with a .proj file) and write plans, progress, questions and handoffs back to them with the mdpm CLI. Use when asked to work on ideas, the flow or "your queue", when MDPM_TASK is set, or before editing an idea file's front matter.
---

`;

const HOOK_COMMAND = '[ -z "$MDPM_TASK" ] || mdpm check --hook';

export interface InitResult {
  file: string;
  action: 'created' | 'updated' | 'unchanged';
}

/**
 * Writes the protocol into `dir`: `.claude/skills/mdpm/SKILL.md` and a section of `AGENTS.md`,
 * both between markers so re-running only replaces the generated part. With `claudeHook`,
 * also adds a Stop hook to `.claude/settings.json`.
 */
export async function agentInit(dir: string, opts: { claudeHook?: boolean } = {}): Promise<InitResult[]> {
  const results: InitResult[] = [];
  const write = async (file: string, update: (old: string) => string) => {
    const exists = existsSync(file);
    const old = exists ? await fs.readFile(file, 'utf8') : '';
    const next = update(old);
    if (exists && next === old) return results.push({ file, action: 'unchanged' });
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, next, 'utf8');
    results.push({ file, action: exists ? 'updated' : 'created' });
  };

  const protocol = protocolMarkdown();
  // The front matter (name, description) is regenerated too, so an older description is replaced.
  const skill = (old: string) => SKILL_FRONT + upsertMarked(old.replace(/^---\n[\s\S]*?\n---\n\n?/, ''), `# mdpm flow protocol\n\n${protocol}`);
  await write(path.join(dir, '.claude', 'skills', 'mdpm', 'SKILL.md'), skill);
  await write(path.join(dir, 'AGENTS.md'), (old) => upsertMarked(old || '# Agent instructions\n', protocol));

  if (opts.claudeHook) {
    await write(path.join(dir, '.claude', 'settings.json'), (old) => {
      let settings: Record<string, unknown> = {};
      if (old.trim()) {
        try {
          settings = JSON.parse(old);
        } catch (e) {
          throw new Error(`.claude/settings.json is not valid JSON (${(e as Error).message}), so the hook was not added. Fix the file, then run "mdpm agent init --claude-hook" again.`);
        }
      }
      const hooks = (settings.hooks ??= {}) as Record<string, unknown[]>;
      const stop = (hooks.Stop ??= []) as { hooks?: { command?: string }[] }[];
      if (!stop.some((g) => g.hooks?.some((h) => h.command?.includes('mdpm check --hook')))) {
        stop.push({ hooks: [{ type: 'command', command: HOOK_COMMAND } as { command: string }] });
      }
      return JSON.stringify(settings, null, 2) + '\n';
    });
  }
  return results;
}
