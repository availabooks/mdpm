import { existsSync, promises as fs } from 'fs';
import * as path from 'path';
import { AGENT_LOG_HEADING, CRITERIA_HEADING, QUESTIONS_HEADING, VERIFICATION_HEADING } from './body';
import { AgentMode } from './types';

/*
 * What agents are told about the protocol: the Claude Code skill, the AGENTS.md section, and
 * the prompt the runner sends for each task. One source, so they never disagree.
 */

export const MARKER_START = '<!-- mdpm:agent-protocol:start (generated by "mdpm agent init"; edits between the markers are overwritten) -->';
export const MARKER_END = '<!-- mdpm:agent-protocol:end -->';

/** The protocol, as markdown. Headings start at level 2 so it can sit inside another document. */
export function protocolMarkdown(): string {
  return `## Working on mdpm tasks

Tasks are markdown files with YAML front matter; projects are folders with a \`.proj\` file.
A task assigned to you (\`owner: <your agent name>\`) is a prompt queued by a person: do it the
way they asked, as if they had typed it to you.

**Change task state only with \`mdpm\` commands.** They validate every write and keep the
board consistent. You may edit the task *body* directly (notes, plan, ticking checkboxes),
but not its front matter. Your name comes from \`$MDPM_AGENT\` (or \`--agent <name>\`).

### Finding work

\`\`\`bash
mdpm next --agent <name> --json     # the best task for you and its mode, or nothing
\`\`\`

| Mode | Task | What to do |
|---|---|---|
| \`resume\` | in-progress, yours | An earlier run stopped. Read the \`## ${AGENT_LOG_HEADING}\` and the branch, then continue. |
| \`implement\` | todo, ready | Do the work on your branch, check every \`## ${CRITERIA_HEADING}\` item, run the \`## ${VERIFICATION_HEADING}\` steps, then hand off. |
| \`refine\` | backlog, or todo without criteria | **Don't change code.** Make the task ready: goal, context, acceptance criteria (\`- [ ] …\`), verification steps, constraints. Then \`mdpm block <id>\` with your questions, so the person reviews the refinement before anyone implements it. |

### Commands

\`\`\`bash
mdpm claim <id>                          # take the task (in-progress, owner: you); first thing you do
mdpm log <id> "<what you did/decided>"   # progress notes, decisions, links; log as you go
mdpm block <id> "<question>" ["<question>"…]   # status blocked; questions go under ## ${QUESTIONS_HEADING}
mdpm handoff <id> "<summary>" --branch <branch> [--pr <url>]   # status review, for a person to check
mdpm release <id> "<reason>"             # give it back (todo) when it isn't a task you should do
mdpm show <id> --json                    # the task, including its body
mdpm check --strict                      # validate everything
\`\`\`

### Rules

- **Block instead of guessing.** If the task is ambiguous, contradicts the code, or needs a
  decision only the person can make, write precise questions with \`mdpm block\` (say what you
  found and the options you see) and stop. Don't invent requirements.
- **Never mark a task done.** Hand off to \`review\`; a person moves it to done. The CLI refuses
  \`done\` while \`MDPM_AGENT\` is set, and refuses changes to tasks you haven't claimed.
- **Work on your branch.** Commit your changes there; never push to or commit on the default branch.
- **Leave a trail.** Before you stop, the task must have a new log entry, a handoff, or a block,
  so the person (or your next run) can pick up from the file alone.
- Keep the task valid: \`mdpm check --strict\` must pass for it.
`;
}

const MODE_INSTRUCTIONS: Record<AgentMode, string> = {
  implement:
    'Mode: implement. Do the work described in the task on the current branch, commit it, verify every acceptance criterion (run the verification steps), tick the criteria you met in the task body, then run `mdpm handoff`. Block with questions instead of guessing.',
  resume:
    'Mode: resume. An earlier run on this task stopped before finishing. Read the task\'s "Agent log" and the commits on this branch, then continue where it left off and finish as in implement mode.',
  refine:
    'Mode: refine. Do NOT change any code. Turn the task into one an agent can implement unattended: fill in Goal, Context (find the relevant files), Acceptance criteria as "- [ ] …" items, Verification (commands/tests), and Constraints, by editing the task body. Then finish with `mdpm block <id> "<question>"…`: ask about anything only the person can decide, and if there is nothing to ask, ask them to review the refinement. The person reviews it and moves it to todo; never move it to todo yourself.',
};

export interface PromptInput {
  agent: string;
  mode: AgentMode;
  taskId: string;
  /** Absolute path of the task file in the main checkout. */
  taskFile: string;
  /** Contents of the task file. */
  taskText: string;
  /** Main checkout, where task state lives (MDPM_ROOT). */
  root: string;
  /** Where to make code changes. */
  worktree: string;
  branch: string;
}

/** The prompt for one task run: the protocol, the mode, the paths, and the task itself. */
export function buildPrompt(p: PromptInput): string {
  return `You are ${p.agent}, working unattended on an mdpm task. Nobody is watching this run, so don't ask for confirmation: act, and when you need a decision from the person, block the task with questions.

${MODE_INSTRUCTIONS[p.mode].replace(/<id>/g, p.taskId)}

- Task id: ${p.taskId}
- Task file (edit its body here, not the copy in your working directory): ${p.taskFile}
- Your working directory is a git worktree on branch "${p.branch}". Make and commit code changes there.
- Task state lives in the main checkout at ${p.root} (MDPM_ROOT is set, so mdpm commands use it).
- The task is already claimed for you. Finish with exactly one of: mdpm handoff ${p.taskId} "<summary>" --branch ${p.branch} · mdpm block ${p.taskId} "<question>" · mdpm release ${p.taskId} "<reason>".${p.mode === 'refine' ? ` In refine mode, finish with mdpm block.` : ''}

${protocolMarkdown()}
## The task

\`\`\`\`markdown
${p.taskText.trim()}
\`\`\`\`
`;
}

/** Replaces the generated block between the markers in `existing`, or appends it. */
export function upsertMarked(existing: string, content: string): string {
  const block = `${MARKER_START}\n${content.trim()}\n${MARKER_END}`;
  const start = existing.indexOf(MARKER_START.slice(0, 30));
  const end = existing.indexOf(MARKER_END);
  if (start >= 0 && end > start) return existing.slice(0, start) + block + existing.slice(end + MARKER_END.length);
  const sep = existing.trim() ? (existing.endsWith('\n') ? '\n' : '\n\n') : '';
  return `${existing}${sep}${block}\n`;
}

const SKILL_FRONT = `---
name: mdpm
description: Find, claim and work on mdpm tasks (markdown files with front matter in folders with a .proj file), and write progress, questions and handoffs back to them with the mdpm CLI. Use when asked to work on tasks, the backlog or "your queue", when MDPM_TASK is set, or before editing a task file's front matter.
---

`;

const HOOK_COMMAND = '[ -z "$MDPM_TASK" ] || mdpm check --hook';

export interface InitResult {
  file: string;
  action: 'created' | 'updated' | 'unchanged';
}

/**
 * Writes the protocol into `dir`: `.claude/skills/mdpm/SKILL.md` and a section of `AGENTS.md`,
 * both between markers so re-running only replaces the generated part. With `claudeHook`,
 * also adds a Stop hook to `.claude/settings.json`.
 */
export async function agentInit(dir: string, opts: { claudeHook?: boolean } = {}): Promise<InitResult[]> {
  const results: InitResult[] = [];
  const write = async (file: string, update: (old: string) => string) => {
    const exists = existsSync(file);
    const old = exists ? await fs.readFile(file, 'utf8') : '';
    const next = update(old);
    if (exists && next === old) return results.push({ file, action: 'unchanged' });
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, next, 'utf8');
    results.push({ file, action: exists ? 'updated' : 'created' });
  };

  const protocol = protocolMarkdown();
  await write(path.join(dir, '.claude', 'skills', 'mdpm', 'SKILL.md'), (old) => upsertMarked(old || SKILL_FRONT, `# mdpm task protocol\n\n${protocol}`));
  await write(path.join(dir, 'AGENTS.md'), (old) => upsertMarked(old || '# Agent instructions\n', protocol));

  if (opts.claudeHook) {
    await write(path.join(dir, '.claude', 'settings.json'), (old) => {
      let settings: Record<string, unknown> = {};
      if (old.trim()) {
        try {
          settings = JSON.parse(old);
        } catch (e) {
          throw new Error(`.claude/settings.json is not valid JSON (${(e as Error).message}), so the hook was not added. Fix the file, then run "mdpm agent init --claude-hook" again.`);
        }
      }
      const hooks = (settings.hooks ??= {}) as Record<string, unknown[]>;
      const stop = (hooks.Stop ??= []) as { hooks?: { command?: string }[] }[];
      if (!stop.some((g) => g.hooks?.some((h) => h.command?.includes('mdpm check --hook')))) {
        stop.push({ hooks: [{ type: 'command', command: HOOK_COMMAND } as { command: string }] });
      }
      return JSON.stringify(settings, null, 2) + '\n';
    });
  }
  return results;
}
